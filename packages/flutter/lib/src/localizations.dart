class KitLocalizationsDelegate extends LocalizationsDelegate<UiLocalizations> {
  const KitLocalizationsDelegate();
  @override
  bool isSupported(Locale locale) =>
      const ['en', 'zh'].contains(locale.languageCode);
  @override
  Future<UiLocalizations> load(Locale locale) =>
      SynchronousFuture(KitLocalizations(locale));
  @override
  bool shouldReload(KitLocalizationsDelegate old) => false;
}

/// Keeps application strings available when a host overrides Prism's strings.
class KitStringsDelegate extends LocalizationsDelegate<KitLocalizations> {
  const KitStringsDelegate();
  @override
  bool isSupported(Locale locale) => KitLocalizations.delegate.isSupported(locale);
  @override
  Future<KitLocalizations> load(Locale locale) => SynchronousFuture(KitLocalizations(locale));
  @override
  bool shouldReload(KitStringsDelegate old) => false;
}
